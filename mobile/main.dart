class Task {
  final String id;
  final String userId;
  final String name;
  final double importance;
  final int estPomodoros;
  final double priorityScore;
  final int sortOrder;
  final bool completed;
  final List<Subtask> subtasks;

  Task({
    required this.id,
    required this.userId,
    required this.name,
    required this.importance,
    required this.estPomodoros,
    required this.priorityScore,
    required this.sortOrder,
    required this.completed,
    required this.subtasks,
  });

  factory Task.fromJson(Map<String, dynamic> json) {
    final rawSubtasks = json['subtasks'] as List? ?? const [];

    return Task(
      id: json['_id'] as String,
      userId: json['userId'] as String,
      name: json['name'] as String,
      importance: (json['importance'] as num).toDouble(),
      estPomodoros: json['estPomodoros'] as int,
      priorityScore: (json['priorityScore'] as num).toDouble(),
      sortOrder: json['sortOrder'] as int,
      completed: json['completed'] as bool,
      subtasks: rawSubtasks
          .map(
            (item) => Subtask.fromJson(Map<String, dynamic>.from(item as Map)),
          )
          .toList(),
    );
  }
}

class Subtask {
  final String id;
  final String parentTaskId;
  final String name;
  final double importance;
  final int estPomodoros;
  final double priorityScore;
  final bool completed;

  Subtask({
