                        onPressed: () async {
                          email = emailController.text;

                          final attempt = await login.forgotPassword(email);
                          if (context.mounted != true) {
                            return;
                          }

                          if (attempt == 200) {
                            Navigator.pushNamed(context, '/passwordcode');
                            return;
                          } else {
                            showDialog(
                              context: context,
                              builder: (context) {
                                return AlertDialog(
                                  title: Text('Error'),
                                  content: Text(
                                    'Error with email. Please try again',
                                  ),
                                  actions: [
                                    TextButton(
                                      onPressed: () {
                                        Navigator.of(context).pop();
                                      },
                                      child: Text('OK'),
                                    ),
                                  ],
                                );
                              },
                            );
                          }
                        },
                      ),
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }
}

