  factory Subtask.fromJson(Map<String, dynamic> json) {
    return Subtask(
      id: json['_id'] as String,
      parentTaskId: json['parentTaskId'] as String,
      name: json['name'] as String,
      importance: (json['importance'] as num).toDouble(),
